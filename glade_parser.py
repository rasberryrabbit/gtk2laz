"""
glade_parser.py
===============
Parse a Glade (GtkBuilder) XML file and produce Lazarus form files.

Outputs for a single .glade file:

  - ``<basename>.lfm`` : Lazarus form resource (text format).
  - ``<basename>.pas`` : Pascal unit declaring the form class with all
                         widget references as published fields so that
                         the LFM streamer can connect them at runtime.
  - Helper ``__init__`` code that wires OnClick/OnChange events to the
    handler stubs generated by ``c_parser``.

The parser walks the ``<interface>`` tree once, materialising a small
``Widget`` node graph. Layout is approximated: GtkBox vertical/horizontal
becomes a TPanel that uses ``ChildSizing.Layout`` so children stack in
order. The original Glade packing properties (expand/fill/position) are
translated into ``Align``/``Anchors`` heuristically.

Limitations (documented in the conversion report):

  * GtkGrid multi-cell spans are flattened to a row of equally-sized
    children inside a TPanel (LCL grid layout is manual).
  * GtkTreeView columns are not in the glade (added at runtime in C);
    the TListView is created with ``vsReport`` and one placeholder column.
  * GtkAdjustment objects are inlined into their owning SpinButton/Scale.
  * CSS styling is dropped; only per-widget properties survive.
"""
from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from typing import Optional

from widget_map import (
    WIDGET_MAP, PROPERTY_MAP, SIGNAL_MAP,
    lookup_widget, apply_property, lookup_signal,
)


# ---------------------------------------------------------------------------
# Widget tree
# ---------------------------------------------------------------------------
@dataclass
class Widget:
    gtk_class: str
    id: str = ""
    lcl_class: str = ""
    pas_unit: str = ""
    kind: str = "leaf"
    properties: dict = field(default_factory=dict)
    signals: list = field(default_factory=list)   # list of (signal, handler, swapped)
    children: list = field(default_factory=list)  # list of Widget
    packing: dict = field(default_factory=dict)
    parent: Optional["Widget"] = None
    # Computed during emission
    pascal_name: str = ""
    pas_field_type: str = ""

    # ------------------------------------------------------------------
    def walk(self):
        yield self
        for c in self.children:
            yield from c.walk()


# ---------------------------------------------------------------------------
# Glade XML -> Widget tree
# ---------------------------------------------------------------------------
class GladeParser:
    def __init__(self, glade_path: str):
        self.glade_path = glade_path
        self.tree = ET.parse(glade_path)
        self.root = self.tree.getroot()  # <interface>
        self.toplevel_objects: list[Widget] = []
        self._id_index: dict[str, Widget] = {}
        # Counter for auto-naming anonymous widgets
        self._anon_counter = 0
        # Reserved Pascal identifiers that need mangling
        self._reserved = {
            "begin","end","if","then","else","while","do","for","to","downto",
            "repeat","until","case","of","with","function","procedure","type",
            "var","const","label","array","record","set","file","class","object",
            "interface","implementation","uses","unit","program","library","package",
            "initialization","finalization","name","result","self","true","false",
            "and","or","not","xor","shl","shr","div","mod","in","is","as","nil",
        }

    # ------------------------------------------------------------------
    def parse(self) -> list[Widget]:
        """Parse the whole <interface> and return toplevel widget list."""
        for obj in self.root.findall("object"):
            w = self._parse_object(obj)
            if w is not None:
                self.toplevel_objects.append(w)
        # Apply heuristic packing
        self._apply_layout(self.toplevel_objects)
        return self.toplevel_objects

    # ------------------------------------------------------------------
    def _parse_object(self, el: ET.Element) -> Optional[Widget]:
        gtk_class = el.get("class", "")
        obj_id = el.get("id", "")
        info = lookup_widget(gtk_class)
        if info is None:
            # Unknown widget: still parse children but mark as TPanel fallback
            lcl_cls, container_lcl, unit, kind = "TPanel", "TPanel", "ExtCtrls", "container"
        else:
            lcl_cls, container_lcl, unit, kind = info
            if lcl_cls is None:
                # Non-widget object (Adjustment, ListStore, etc.) - skip but index
                return None
        w = Widget(
            gtk_class=gtk_class,
            id=obj_id,
            lcl_class=lcl_cls,
            pas_unit=unit,
            kind=kind,
        )
        w.pascal_name = self._pascalize_name(obj_id, lcl_cls)
        w.pas_field_type = lcl_cls
        # Parse properties
        for prop in el.findall("property"):
            name = prop.get("name", "")
            val = (prop.text or "").strip()
            if name:
                w.properties[name] = val
        # Parse signals
        for sig in el.findall("signal"):
            name = sig.get("name", "")
            handler = sig.get("handler", "")
            # handler is like "G_CALLBACK(Xclose)" — strip the macro
            m = re.match(r"G_CALLBACK\(\s*([A-Za-z_]\w*)\s*\)", handler)
            if m:
                handler = m.group(1)
            elif handler.startswith("G_CALLBACK("):
                handler = handler[len("G_CALLBACK("):].rstrip(")").strip()
            w.signals.append((name, handler, sig.get("swapped", "no") == "yes"))
        # Parse children recursively. Notebook children may have
        # type="tab" (the tab label widget) or no type (page content).
        # We pair them so the page widget knows its tab caption.
        page_tabs: dict[int, str] = {}   # page_index -> tab_label_text
        page_widgets: list[Widget] = []
        tab_widgets: list[Widget] = []
        for child_el in el.findall("child"):
            sub_obj = child_el.find("object")
            if sub_obj is None:
                continue
            sub = self._parse_object(sub_obj)
            if sub is None:
                continue
            sub.parent = w
            child_type = child_el.get("type", "")
            # Packing properties
            packing_el = child_el.find("packing")
            if packing_el is not None:
                for p in packing_el.findall("property"):
                    sub.packing[p.get("name", "")] = (p.text or "").strip()
            if child_type == "tab":
                tab_widgets.append(sub)
            else:
                page_widgets.append(sub)
                w.children.append(sub)
        # If this is a notebook, attach tab labels to pages in order.
        if w.gtk_class == "GtkNotebook":
            for i, page in enumerate(page_widgets):
                if i < len(tab_widgets):
                    tab = tab_widgets[i]
                    # Tab label is usually a GtkLabel with 'label' property
                    caption = tab.properties.get("label", "")
                    if not caption:
                        caption = tab.id or f"Tab {i+1}"
                    page.properties["_tab_caption"] = caption
        # Index by id
        if obj_id:
            self._id_index[obj_id] = w
        return w

    # ------------------------------------------------------------------
    def _pascalize_name(self, raw: str, lcl_class: str) -> str:
        """Convert glade id (e.g. 'OPEN_T') to a Pascal identifier."""
        if not raw:
            self._anon_counter += 1
            raw = f"{lcl_class}_{self._anon_counter}"
        # Snake-CASE -> PascalCase, preserving readability
        parts = re.split(r"[_\W]+", raw)
        name = "".join(p[:1].upper() + p[1:].lower() for p in parts if p)
        if not name:
            name = lcl_class
        # Ensure it doesn't start with a digit
        if name[0].isdigit():
            name = "W" + name
        # Avoid clashing with Pascal keywords
        if name.lower() in self._reserved:
            name = name + "_"
        return name

    # ------------------------------------------------------------------
    def _apply_layout(self, widgets: list[Widget]) -> None:
        """Walk the tree and apply layout heuristics based on parent type."""
        for w in widgets:
            self._layout_node(w)
            self._apply_layout(w.children)

    def _layout_node(self, w: Widget) -> None:
        """Set Align/Anchors based on parent orientation and packing."""
        parent = w.parent
        if parent is None:
            return
        # Form root child: align client
        if parent.gtk_class == "GtkWindow" and parent.kind == "form":
            if w.gtk_class in ("GtkStatusbar",):
                w.properties.setdefault("_align", "alBottom")
            elif w.gtk_class in ("GtkToolbar",):
                w.properties.setdefault("_align", "alTop")
            elif w.gtk_class in ("GtkMenuBar",):
                w.properties.setdefault("_align", "alTop")
            else:
                w.properties.setdefault("_align", "alClient")
            return
        # Box: stack children according to orientation
        if parent.gtk_class == "GtkBox":
            orient = parent.properties.get("orientation", "horizontal")
            pack_type = w.packing.get("pack-type", "start")
            expand = w.packing.get("expand", "False")
            if expand == "True":
                w.properties.setdefault("_align",
                                        "alClient" if orient == "vertical" else "alLeft")
            else:
                # Non-expanded children keep their natural height/width:
                # use alNone (free positioning) by default. For toolbars,
                # we still want them to span horizontally so use alLeft/alTop.
                if w.gtk_class in ("GtkStatusbar",):
                    w.properties.setdefault("_align", "alBottom")
                elif w.gtk_class in ("GtkToolbar", "GtkMenuBar"):
                    w.properties.setdefault("_align", "alTop")
                else:
                    w.properties.setdefault("_align", "alNone")
            return
        # Notebook: each child becomes a TabSheet (handled specially in emitter)
        if parent.gtk_class == "GtkNotebook":
            w.properties.setdefault("_align", "alClient")
            return
        # ScrolledWindow: client
        if parent.gtk_class == "GtkScrolledWindow":
            w.properties.setdefault("_align", "alClient")
            return
        # Toolbar children: do NOT set Align (LCL toolbuttons use Left/Top)
        if parent.gtk_class == "GtkToolbar":
            # ToolButtons should not have Align set
            return
        # Frame / Grid / Generic container: child fills client
        w.properties.setdefault("_align", "alClient")


# ---------------------------------------------------------------------------
# LFM emitter
# ---------------------------------------------------------------------------
class LfmEmitter:
    """Render a Widget tree as a Lazarus .lfm text resource."""

    def __init__(self, form_root: Widget, form_class_name: str,
                 form_var_name: str = ""):
        self.root = form_root
        self.form_class = form_class_name
        # The LFM object line uses the *variable* name (e.g. MainForm),
        # not the class name (TMainForm). Default: strip leading 'T'.
        if form_var_name:
            self.form_var = form_var_name
        else:
            self.form_var = (form_class_name[1:] if form_class_name.startswith("T")
                             else form_class_name)
        self.lines: list[str] = []
        self.indent = 0
        self.widget_count = 0
        self.skipped: list[str] = []   # widgets that were dropped
        self.notes: list[str] = []

    # ------------------------------------------------------------------
    def emit(self) -> str:
        self.lines = []
        self.lines.append(f"object {self.form_var}: {self.form_class}")
        self.indent = 2
        self.widget_count += 1
        # Form-level properties from GtkWindow
        self._emit_widget_props(self.root, is_form=True)
        # Note: do not emit an explicit "object" line for children of TForm
        # when they are non-visual (TMainMenu). The LFM allows them inline.
        for child in self.root.children:
            self._emit_child(child)
        self.lines.append("end")
        return "\n".join(self.lines) + "\n"

    # ------------------------------------------------------------------
    def _emit_child(self, w: Widget) -> None:
        if w.lcl_class == "TMainMenu":
            self._emit_menu(w)
            return
        if w.lcl_class == "TPopupMenu":
            self._emit_menu(w, popup=True)
            return
        self.widget_count += 1
        pad = " " * self.indent
        self.lines.append(f"{pad}object {w.pascal_name}: {w.lcl_class}")
        self.indent += 2
        try:
            self._emit_widget_props(w)
            # Notebook -> render children as TabSheet objects
            if w.gtk_class == "GtkNotebook":
                self._emit_notebook_tabs(w)
            elif w.kind == "container":
                for c in w.children:
                    self._emit_child(c)
        finally:
            self.indent -= 2
        pad = " " * self.indent
        self.lines.append(f"{pad}end")

    # ------------------------------------------------------------------
    def _emit_widget_props(self, w: Widget, is_form: bool = False) -> None:
        pad = " " * self.indent
        # Name (form's Name is set by LFM parent context; skip for form root)
        if not is_form:
            self.lines.append(f"{pad}Name = '{w.pascal_name}'")
        # Apply align
        align = w.properties.get("_align")
        if align and align != "alNone":
            self.lines.append(f"{pad}Align = {align}")
        # Apply mapped properties
        emitted_keys = set()
        # Skip glade's "name" property: it's a CSS name in GTK, not the
        # LCL component Name (which we already emitted above).
        skip_props = {"name"}
        for k, v in w.properties.items():
            if k.startswith("_"):
                continue
            if k in skip_props:
                continue
            out = apply_property(w.gtk_class, k, v)
            if out is None:
                continue
            lfm_key, lfm_val = out
            if lfm_val is None or lfm_key is None:
                continue
            if lfm_key in emitted_keys:
                continue
            emitted_keys.add(lfm_key)
            # Compound key like 'BorderSpacing.Around' -> nested block
            if "." in lfm_key:
                top, sub = lfm_key.split(".", 1)
                self.lines.append(f"{pad}{top}.{sub} = {lfm_val}")
            else:
                self.lines.append(f"{pad}{lfm_key} = {lfm_val}")
        # Notebook show-tabs etc handled by mapping
        # ToolButton style for separators
        if w.gtk_class == "GtkSeparatorToolItem":
            self.lines.append(f"{pad}Style = tbsSeparator")
        # TSpeedButton configuration for toggle buttons
        if w.gtk_class == "GtkToggleButton":
            self.lines.append(f"{pad}AllowAllUp = True")
            self.lines.append(f"{pad}GroupIndex = 0")
        # Signals -> LCL events
        for sig_name, handler, swapped in w.signals:
            sig_info = lookup_signal(sig_name)
            if sig_info is None:
                self.notes.append(f"Unmapped signal '{sig_name}' on {w.pascal_name}")
                continue
            event_name, kind = sig_info
            if handler:
                self.lines.append(f"{pad}{event_name} = @{handler}")

    # ------------------------------------------------------------------
    def _emit_notebook_tabs(self, w: Widget) -> None:
        """Convert GtkNotebook children to TTabSheet objects."""
        pad = " " * self.indent
        for idx, child in enumerate(w.children):
            # Each notebook <child> in glade is typically wrapped with a
            # GtkBox or similar as the page content; we create a TabSheet
            # and nest the content under it.
            self.widget_count += 1
            tab_name = f"{w.pascal_name}_Tab{idx+1}"
            # Caption comes from the matching <child type="tab"> label.
            caption = child.properties.get("_tab_caption", f"Tab {idx+1}")
            # Escape single quotes
            caption_esc = caption.replace("'", "''")
            self.lines.append(f"{pad}object {tab_name}: TTabSheet")
            self.indent += 2
            try:
                pad2 = " " * self.indent
                self.lines.append(f"{pad2}Caption = '{caption_esc}'")
                # Emit the actual page content as a child
                self._emit_child(child)
            finally:
                self.indent -= 2
            self.lines.append(f"{pad}end")

    # ------------------------------------------------------------------
    def _emit_menu(self, w: Widget, popup: bool = False) -> None:
        pad = " " * self.indent
        self.lines.append(f"{pad}object {w.pascal_name}: {w.lcl_class}")
        self.indent += 2
        try:
            pad2 = " " * self.indent
            self.lines.append(f"{pad2}Name = '{w.pascal_name}'")
            for child in w.children:
                self._emit_menu_item(child, pad2)
        finally:
            self.indent -= 2
        self.lines.append(f"{pad}end")

    def _emit_menu_item(self, w: Widget, pad: str) -> None:
        sub_pad = pad + "  "
        self.lines.append(f"{pad}object Item{iid(w.pascal_name)}: TMenuItem")
        self.lines.append(f"{sub_pad}Caption = '{w.properties.get('label', '')}'")
        if w.gtk_class == "GtkCheckMenuItem":
            active = w.properties.get("active", "False")
            self.lines.append(f"{sub_pad}Checked = {_bool_str(active)}")
        if w.gtk_class == "GtkSeparatorMenuItem":
            self.lines.append(f"{sub_pad}Caption = '-'")
        for sig_name, handler, _ in w.signals:
            if sig_name == "activate" and handler:
                self.lines.append(f"{sub_pad}OnClick = @{handler}")
        for child in w.children:
            self._emit_menu_item(child, sub_pad)
        self.lines.append(f"{pad}end")


def iid(name: str) -> str:
    """Make a Pascal identifier from a name (used for menu items)."""
    if not name:
        return "MenuItem1"
    return re.sub(r"\W", "", name) or "MenuItem1"


def _bool_str(v: str) -> str:
    return "True" if v in ("True", "true", "1", "yes") else "False"


# ---------------------------------------------------------------------------
# Pascal form unit emitter
# ---------------------------------------------------------------------------
class PasFormEmitter:
    """Render the .pas unit that backs a form."""

    def __init__(self, form_root: Widget, form_class_name: str,
                 unit_name: str, used_units: list[str] = None,
                 form_var_name: str = "", glade_path: str = ""):
        self.root = form_root
        self.form_class = form_class_name
        self.unit_name = unit_name
        self.used_units = list(used_units or [])
        self.glade_path = glade_path
        # Form instance variable name: default strips the leading 'T'.
        if form_var_name:
            self.form_var = form_var_name
        else:
            self.form_var = (form_class_name[1:] if form_class_name.startswith("T")
                             else form_class_name)
        # collected unique units needed for component types
        self._units: set[str] = set()

    # ------------------------------------------------------------------
    def emit(self) -> str:
        out: list[str] = []
        # Collect required units from widgets
        for w in self.root.walk():
            if w.pas_unit:
                self._units.add(w.pas_unit)
        # Standard units always needed
        self._units.update({"Classes", "SysUtils", "Forms", "Controls",
                            "Graphics", "Dialogs"})
        out.append(f"unit {self.unit_name};")
        out.append("")
        out.append("{$mode objfpc}{$H+}")
        out.append("")
        out.append("interface")
        out.append("")
        out.append("uses")
        unit_list = sorted(self._units)
        # Comma-separate, last one without comma
        for i, u in enumerate(unit_list):
            sep = "," if i < len(unit_list) - 1 else ";"
            out.append(f"  {u}{sep}")
        out.append("")
        out.append("type")
        out.append(f"  {self.form_class} = class(TForm)")
        # Published component fields (required for LFM streaming)
        for w in self.root.walk():
            if w is self.root:
                continue
            if w.lcl_class in ("TMainMenu", "TPopupMenu", "TMenuItem"):
                # still emit as fields
                pass
            if not w.pascal_name or not w.lcl_class:
                continue
            out.append(f"    {w.pascal_name}: {w.lcl_class};")
        out.append("    procedure FormCreate(Sender: TObject);")
        out.append("    procedure FormClose(Sender: TObject; var CloseAction: TCloseAction);")
        out.append("  private")
        out.append("  public")
        out.append("  end;")
        out.append("")
        out.append("var")
        out.append(f"  {self.form_var}: {self.form_class};")
        out.append("")
        out.append("implementation")
        out.append("")
        # Collect event handler signatures
        handlers = self._collect_handlers()
        if handlers:
            out.append("{$R *.lfm}")
            out.append("")
            for h_name, h_kind in handlers.items():
                sig = self._handler_signature(h_name, h_kind)
                body = self._handler_body(h_name, h_kind)
                out.append(f"procedure {self.form_class}.{sig};")
                out.append("begin")
                out.append(f"  {body}")
                out.append("end;")
                out.append("")
        else:
            out.append("{$R *.lfm}")
            out.append("")
        out.append(f"procedure {self.form_class}.FormCreate(Sender: TObject);")
        out.append("begin")
        out.append("  // Initialize form - hook up runtime state here.")
        out.append("end;")
        out.append("")
        out.append(f"procedure {self.form_class}.FormClose(Sender: TObject; var CloseAction: TCloseAction);")
        out.append("begin")
        out.append("  CloseAction := caFree;")
        out.append("end;")
        out.append("")
        out.append("end.")
        return "\n".join(out) + "\n"

    # ------------------------------------------------------------------
    def _collect_handlers(self) -> dict[str, str]:
        """Walk widgets and collect unique event handler -> signature kind."""
        result: dict[str, str] = {}
        for w in self.root.walk():
            for sig_name, handler, _ in w.signals:
                if not handler:
                    continue
                info = lookup_signal(sig_name)
                if info is None:
                    result.setdefault(handler, "click")
                    continue
                _, kind = info
                # Prefer more specific kinds (e.g. destroy > click)
                existing = result.get(handler)
                if existing is None or (kind == "destroy" and existing == "click"):
                    result[handler] = kind
        # Also scan the input C source for g_signal_connect calls and add
        # their handler names as stubs. These are wired at runtime in C and
        # therefore not declared in the glade file, but the form unit must
        # still declare them so the LCL streaming mechanism can resolve
        # OnClick := @Handler references.
        for h_name, h_kind in _scan_c_handlers(self.glade_path).items():
            existing = result.get(h_name)
            if existing is None:
                result[h_name] = h_kind
        return result

    def _handler_signature(self, name: str, kind: str) -> str:
        if kind == "click":
            return f"{name}(Sender: TObject)"
        if kind == "change":
            return f"{name}(Sender: TObject)"
        if kind == "toggle":
            return f"{name}(Sender: TObject)"
        if kind == "valuechg":
            return f"{name}(Sender: TObject)"
        if kind == "keypress":
            return f"{name}(Sender: TObject; var Key: Word; Shift: TShiftState)"
        if kind == "mouse":
            return (f"{name}(Sender: TObject; Button: TMouseButton; "
                    "Shift: TShiftState; X, Y: Integer)")
        if kind == "select":
            return f"{name}(Sender: TObject; User: boolean)"
        if kind == "destroy":
            return f"{name}(Sender: TObject; var CloseAction: TCloseAction)"
        return f"{name}(Sender: TObject)"

    def _handler_body(self, name: str, kind: str) -> str:
        return (f"// TODO: port original C handler '{name}'. "
                "Body left empty by gtk2laz converter.")


# ---------------------------------------------------------------------------
# Top-level entry: parse + emit
# ---------------------------------------------------------------------------
def _scan_c_handlers(glade_path: str) -> dict[str, str]:
    """Scan all .c files in the same directory as the glade file for
    ``g_signal_connect`` calls and return a dict of handler-name -> kind.

    The "kind" is determined from the GTK signal name (e.g. ``clicked``
    -> ``click``, ``toggled`` -> ``toggle``, ``key-press-event`` ->
    ``keypress``).
    """
    import glob
    handlers: dict[str, str] = {}
    src_dir = os.path.dirname(glade_path)
    # Patterns: g_signal_connect(w, "signal", G_CALLBACK(handler), data)
    #           g_signal_connect(G_OBJECT(w), "signal", G_CALLBACK(handler), ...)
    pat = re.compile(
        r'g_signal_connect(?:_swapped)?\s*\(\s*[^,]+,\s*'
        r'"(?P<sig>[^"]+)"\s*,\s*'
        r'G_CALLBACK\s*\(\s*(?P<h>[A-Za-z_]\w*)\s*\)',
        re.DOTALL,
    )
    for c_file in glob.glob(os.path.join(src_dir, "*.c")):
        try:
            with open(c_file, "r", encoding="utf-8", errors="replace") as f:
                src = f.read()
        except OSError:
            continue
        for m in pat.finditer(src):
            sig = m.group("sig")
            h = m.group("h")
            info = lookup_signal(sig)
            kind = info[1] if info else "click"
            existing = handlers.get(h)
            if existing is None or (kind == "destroy" and existing == "click"):
                handlers[h] = kind
    return handlers


def convert_glade(glade_path: str, out_dir: str,
                  unit_name: str = "mainform",
                  form_class_name: str = "TMainForm") -> dict:
    """Convert one .glade file into .lfm + .pas under ``out_dir``.

    Returns a dict describing what was converted (for the report).
    """
    parser = GladeParser(glade_path)
    parser.parse()

    # Find the form root (first GtkWindow in toplevels)
    form_root = None
    other_toplevels: list[Widget] = []
    for w in parser.toplevel_objects:
        if w.gtk_class in ("GtkWindow", "GtkDialog", "GtkMessageDialog",
                           "GtkAboutDialog") and form_root is None:
            form_root = w
        else:
            other_toplevels.append(w)

    if form_root is None:
        # Fall back to first toplevel
        if parser.toplevel_objects:
            form_root = parser.toplevel_objects[0]
            other_toplevels = parser.toplevel_objects[1:]
        else:
            raise ValueError("No toplevel widget found in glade file")

    # Form variable name = class name minus leading 'T'
    form_var = (form_class_name[1:] if form_class_name.startswith("T")
                else form_class_name)
    # Override class name on the root so the LFM declares a TForm descendant.
    # The form's pascal_name stays as the variable name (e.g. MainForm) since
    # the LFM object line uses the instance variable.
    form_root.lcl_class = form_class_name
    form_root.pascal_name = form_var

    emitter = LfmEmitter(form_root, form_class_name, form_var_name=form_var)
    lfm_text = emitter.emit()

    pas_emitter = PasFormEmitter(form_root, form_class_name, unit_name,
                                  form_var_name=form_var,
                                  glade_path=glade_path)
    pas_text = pas_emitter.emit()

    os.makedirs(out_dir, exist_ok=True)
    lfm_path = os.path.join(out_dir, unit_name + ".lfm")
    pas_path = os.path.join(out_dir, unit_name + ".pas")
    with open(lfm_path, "w", encoding="utf-8") as f:
        f.write(lfm_text)
    with open(pas_path, "w", encoding="utf-8") as f:
        f.write(pas_text)

    return {
        "lfm_path": lfm_path,
        "pas_path": pas_path,
        "widget_count": emitter.widget_count,
        "skipped": emitter.skipped,
        "notes": emitter.notes,
        "other_toplevels": [w.gtk_class + ":" + (w.id or "?")
                            for w in other_toplevels],
        "form_class": form_class_name,
        "unit_name": unit_name,
    }
